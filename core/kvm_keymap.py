def mac_vk_to_hid(vk: int) -> int | None:
    hid = MAC_VK_TO_HID.get(vk)
    if hid is None or hid in EXCLUDED_HID:
        return None
    return hid


def hid_to_mac_vk(hid: int) -> int | None:
    if hid in EXCLUDED_HID:
        return None
    return HID_TO_MAC_VK.get(hid)



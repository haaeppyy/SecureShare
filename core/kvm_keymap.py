"""Keycode tables for keyboard/mouse sharing.

The canonical transport key space is the USB HID keyboard usage code.
Each platform converts to and from HID with a pure-data table:

    macOS capture:    mac virtual keycode  -> HID   (MAC_VK_TO_HID)
    macOS injection:  HID -> mac virtual keycode    (HID_TO_MAC_VK, inverse)
    Windows capture:  PS/2 scan code (+extended) -> HID (WIN_SCAN_TO_HID)
    Windows injection: HID -> PS/2 scan code (+extended) (HID_TO_WIN_SCAN)

Scan-code injection (rather than VK codes) preserves the user's keyboard
layout. The 0xE0 extended prefix is modelled with a bool flag.

v1 scope: the standard 104-key US set plus modifiers. Anything outside
the tables is dropped at capture time (never forwarded); media keys, IME
and dead keys are out of scope.
"""

# -- modifier masks ---------------------------------------------------------

MOD_SHIFT = 1
MOD_CTRL = 2
MOD_ALT = 4
MOD_META = 8
MOD_ALTGR = 16

# HID modifier usages -> mask bit(s).
MODIFIER_HID_TO_MASK = {
    0x94: MOD_CTRL,   # Left Control
    0x95: MOD_SHIFT,  # Left Shift
    0x96: MOD_ALT,    # Left Alt
    0x97: MOD_META,   # Left GUI (Command / Meta / Super)
    0x98: MOD_CTRL,   # Right Control
    0x99: MOD_SHIFT,  # Right Shift
    0x9A: MOD_ALTGR,  # Right Alt (AltGr)
    0x9B: MOD_META,   # Right GUI
}

# Canonical HID code to (re)press when reconciling a modifier mask.
MODIFIER_MASK_TO_HID = {
    MOD_SHIFT: 0x95,
    MOD_CTRL: 0x94,
    MOD_ALT: 0x96,
    MOD_META: 0x97,
    MOD_ALTGR: 0x9A,
}

# Emergency escape chord: Ctrl + Alt + Space (HID).
ESCAPE_CHORD_HID = frozenset((0x94, 0x96, 0x2C))

# HID codes excluded from forwarding (non-US, power, F13-F24, IME/Lang).
# 0x48 (Pause) collides with Num Lock on PS/2 (both 0x45); Pause needs the
# E1 1D 45 sequence, so it is excluded from Windows injection.
EXCLUDED_HID = frozenset({0x32, 0x48, 0x64, 0x66} | set(range(0x68, 0x94)))


def hid_is_modifier(hid: int) -> bool:
    return hid in MODIFIER_HID_TO_MASK


def modifier_mask_for_hid(hid: int) -> int:
    return MODIFIER_HID_TO_MASK.get(hid, 0)


def modifier_hids_for_mask(mask: int) -> list[int]:
    """Left-variant HID codes to press for a mask (AltGr stays right Alt)."""
    out = []
    for bit, hid in MODIFIER_MASK_TO_HID.items():
        if mask & bit:
            out.append(hid)
    return out


